import { SITE_URL } from '../config/site';
import { localeMeta, type Locale } from '../i18n/config';
import type { CaseStudy } from './caseStudies';
import { t, type MessageKey } from '../i18n/messages';

const descriptionKeys: Partial<Record<string, MessageKey>> = {
  'react-smart-copy': 'seo.smartCopyDescription',
  'react-inp-chunker': 'seo.inpChunkerDescription',
  'design-system-uplift': 'seo.designSystemDescription',
  'frontend-quality-system': 'seo.qualitySystemDescription',
  'performance-modernization': 'seo.performanceDescription',
};

export const getCaseStudyDescription = (
  locale: Locale,
  caseStudy: CaseStudy,
) => {
  const key = descriptionKeys[caseStudy.slug];
  return key ? t(locale, key) : caseStudy.description;
};

/** Generated by scripts/generate-og.mjs; shared by every locale. */
export const getCaseStudyOgImage = (slug: string) =>
  `/images/work/${slug}-og-1200x630.png`;

/** One TechArticle per case study; the page body is not repeated in JSON-LD. */
export const getCaseStudyArticleSchema = (
  locale: Locale,
  caseStudy: CaseStudy,
  url: string,
) => ({
  '@context': 'https://schema.org',
  '@type': 'TechArticle',
  '@id': `${url}#article`,
  headline: caseStudy.title,
  description: getCaseStudyDescription(locale, caseStudy),
  url,
  image: `${SITE_URL}${getCaseStudyOgImage(caseStudy.slug)}`,
  author: { '@id': `${SITE_URL}/#person` },
  publisher: { '@id': `${SITE_URL}/#person` },
  datePublished: `${caseStudy.datePublished}T00:00:00+05:30`,
  dateModified: `${caseStudy.dateModified}T00:00:00+05:30`,
  inLanguage: localeMeta[locale].htmlLang,
  about: caseStudy.relatedServices,
  mainEntityOfPage: { '@id': `${url}#webpage` },
});
